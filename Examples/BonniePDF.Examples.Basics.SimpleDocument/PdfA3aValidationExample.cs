using BonniePDF;

namespace BonniePDF.Examples.Basics.SimpleDocument;

/// <summary>
/// Minimal PDF/A-3a fixture consumed by the independent veraPDF release gate.
/// Keep this logically equivalent to the TypeScript gate fixture.
///
/// The "a" levels mandate tagged structure on top of the underlying "b"
/// requirements, so this pairs PDF/A-3a with PDF/UA-1 and a document language.
/// Without a fixture claiming part=3 conformance=A, the gate — which validates
/// whatever each file's own XMP claims — never exercises the level at all.
/// </summary>
public static class PdfA3aValidationExample
{
    public static Document Generate()
    {
        Document doc = new()
        {
            Metadata = new DocumentMetadata
            {
                Title = "BonniePDF PDF/A-3a validation sample",
                Author = "BonniePDF validation harness",
                Producer = "BonniePDF",
            },
            Settings = new DocumentSettings
            {
                Conformance = PdfAConformance.PdfA3a,
                Accessibility = AccessibilityMode.PdfUa1,
                Language = "en-GB",
            },
        };

        doc.Add(new TextBlock
        {
            Text = "PDF/A-3a baseline validation sample generated by BonniePDF.",
            FontName = StandardFonts.Helvetica,
            FontSize = 12,
        });

        return doc;
    }
}
