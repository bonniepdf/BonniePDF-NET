using BonniePDF.Configuration;
using BonniePDF.Core;
using BonniePDF.Elements.Text;
using BonniePDF.Typography;

namespace BonniePDF.Examples.Basics.SimpleDocument;

/// <summary>
/// Minimal PDF/A-4 fixture consumed by the independent veraPDF release gate.
/// Keep this logically equivalent to the TypeScript gate fixture.
/// </summary>
public static class PdfA4ValidationExample
{
    public static Document Generate()
    {
        Document doc = new()
        {
            Metadata = new DocumentMetadata
            {
                Title = "BonniePDF PDF/A-4 validation sample",
                Author = "BonniePDF validation harness",
                Producer = "BonniePDF",
            },
            Settings = new DocumentSettings
            {
                Conformance = PdfAConformance.PdfA4,
            },
        };

        doc.Add(new TextBlock
        {
            Text = "PDF/A-4 baseline validation sample generated by BonniePDF.",
            FontName = StandardFonts.Helvetica,
            FontSize = 12,
        });

        return doc;
    }
}
