using BonniePDF;

namespace BonniePDF.Examples.ComplianceArchival.PdfCompliance;

/// <summary>
/// Minimal PDF/UA-2 with PDF/A-4 fixture consumed by the independent veraPDF release gate.
/// Keep this logically equivalent to the TypeScript gate fixture.
/// </summary>
public static class PdfUa2ValidationExample
{
    /// <summary>Builds the document. Export the result with GenerateBytes() or GenerateBytesAsync().</summary>
    public static Document Generate()
    {
        Document doc = new()
        {
            Metadata = new DocumentMetadata
            {
                Title = "BonniePDF PDF/UA-2 validation sample",
                Author = "BonniePDF validation harness",
                Producer = "BonniePDF",
            },
            Settings = new DocumentSettings
            {
                Conformance = PdfAConformance.PdfA4,
                Accessibility = AccessibilityMode.PdfUa2,
                Language = "en-GB",
            },
        };

        doc.Add(new Heading("PDF/UA-2 validation sample") { Level = 1, TocIdentifier = "Sample" });
        doc.Add(new TextBlock
        {
            Text = "PDF/UA-2 and PDF/A-4 baseline validation sample generated by BonniePDF.",
            FontName = StandardFonts.Helvetica,
            FontSize = 12,
        });
        var list = new OrderedList();
        list.AddItem("Tagged in the PDF 2.0 structure namespace");
        list.AddItem("Links and bookmarks reach their headings");
        doc.Add(list);
        doc.Add(new SectionLink("Back to the heading", "Sample"));

        return doc;
    }
}
