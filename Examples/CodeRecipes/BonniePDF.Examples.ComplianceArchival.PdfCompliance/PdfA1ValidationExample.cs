using BonniePDF;

namespace BonniePDF.Examples.ComplianceArchival.PdfCompliance;

/// <summary>
/// Minimal PDF/A-1b and PDF/A-1a fixtures consumed by the independent veraPDF
/// release gate. Keep these logically equivalent to the TypeScript gate fixtures.
///
/// PDF/A-1 is the PDF 1.4-era generation. The engine emits a 1.7 header for it
/// (PDF/A-4 is the only level that moves the version), which reads like a
/// conflict with ISO 19005-1 — but veraPDF validates both levels as compliant,
/// so the machine-verifiable claim holds. Both are in the corpus precisely so
/// that any future divergence surfaces as a failing gate rather than an
/// assumption.
/// </summary>
public static class PdfA1ValidationExample
{
    /// <summary>PDF/A-1b: visual reproducibility only, no tagging required.</summary>
    public static Document GenerateBasic() => Build(PdfAConformance.PdfA1b, "b");

    /// <summary>PDF/A-1a: adds the tagged structure the "a" levels mandate.</summary>
    public static Document GenerateAccessible() => Build(PdfAConformance.PdfA1a, "a");

    private static Document Build(PdfAConformance conformance, string suffix)
    {
        Document doc = new()
        {
            Metadata = new DocumentMetadata
            {
                Title = $"BonniePDF PDF/A-1{suffix} validation sample",
                Author = "BonniePDF validation harness",
                Producer = "BonniePDF",
            },
            Settings = new DocumentSettings
            {
                Conformance = conformance,
            },
        };

        if (conformance == PdfAConformance.PdfA1a)
        {
            doc.Settings.Accessibility = AccessibilityMode.PdfUa1;
            doc.Settings.Language = "en-GB";
        }

        doc.Add(new TextBlock
        {
            Text = $"PDF/A-1{suffix} baseline validation sample generated by BonniePDF.",
            FontName = StandardFonts.Helvetica,
            FontSize = 12,
        });

        return doc;
    }
}
