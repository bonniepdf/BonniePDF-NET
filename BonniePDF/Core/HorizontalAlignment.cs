namespace BonniePDF;

/// <summary>
/// Horizontal alignment options for layout elements
/// </summary>
public enum HorizontalAlignment
{
    /// <summary>Align to the start (left for LTR languages)</summary>
    Start,

    /// <summary>Align to the center</summary>
    Center,

    /// <summary>Align to the end (right for LTR languages)</summary>
    End,

    /// <summary>Stretch to fill available space</summary>
    Stretch
}